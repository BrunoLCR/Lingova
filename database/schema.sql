-- Definir tarifa por hora: cierra la vigente y abre la nueva (solo con permiso tarifas:gestionar)
create or replace function public.establecer_tarifa(p_docente uuid, p_tarifa numeric, p_moneda text default 'PEN', p_desde date default current_date)
returns bigint language plpgsql security definer set search_path = public as $$
declare v_id bigint;
begin
  if not public.tiene_permiso('tarifas:gestionar') then raise exception 'Sin permiso tarifas:gestionar' using errcode = '42501'; end if;
  if not exists (select 1 from public.profiles where id = p_docente and role = 'PROFESOR') then
    raise exception 'El beneficiario debe ser un docente' using errcode = '22023'; end if;
  update public.tarifas_docentes set vigente_hasta = greatest(vigente_desde, p_desde - 1)
   where docente_id = p_docente and moneda = p_moneda and vigente_hasta is null;
  insert into public.tarifas_docentes (docente_id, tarifa_hora, moneda, vigente_desde, creado_por)
  values (p_docente, p_tarifa, p_moneda, p_desde, auth.uid()) returning id into v_id;
  insert into public.eventos_auditoria (tipo_evento, entidad, entidad_id, usuario_id, descripcion, datos)
  values ('TARIFA_ESTABLECIDA', 'tarifas_docentes', v_id::text, auth.uid(), 'Nueva tarifa por hora',
          jsonb_build_object('docente_id', p_docente, 'tarifa_hora', p_tarifa, 'moneda', p_moneda, 'desde', p_desde));
  return v_id;
end $$;
revoke all on function public.establecer_tarifa(uuid,numeric,text,date) from public;
grant execute on function public.establecer_tarifa(uuid,numeric,text,date) to authenticated;

-- Hash SHA-256 de un evento (misma fórmula en trigger y en verificación)
create or replace function public.calcular_hash_evento(
  p_id bigint, p_hash_anterior text, p_tipo text, p_entidad text, p_entidad_id text,
  p_usuario uuid, p_rol text, p_descripcion text, p_datos jsonb, p_fecha timestamptz
) returns text language sql immutable set search_path = public as $$
  select encode(sha256(convert_to(concat_ws('|',
    p_id::text, p_hash_anterior, p_tipo, coalesce(p_entidad,''), coalesce(p_entidad_id,''),
    coalesce(p_usuario::text,''), coalesce(p_rol,''), coalesce(p_descripcion,''),
    p_datos::text, to_char(p_fecha at time zone 'UTC','YYYY-MM-DD"T"HH24:MI:SS.US')
  ), 'UTF8')), 'hex');
$$;

-- Trigger BEFORE INSERT: encadena y firma cada evento (el cliente no puede falsificar hashes)
create or replace function public.trg_eventos_auditoria_hash()
returns trigger language plpgsql security definer set search_path = public as $$
declare v_prev text;
begin
  perform pg_advisory_xact_lock(710001);               -- serializa la cadena
  select hash_integridad into v_prev from public.eventos_auditoria order by id desc limit 1;
  new.hash_anterior := coalesce(v_prev, 'GENESIS');
  new.created_at := clock_timestamp();
  if new.usuario_id is not null then
    new.rol_usuario := (select role from public.profiles where id = new.usuario_id);
  end if;
  new.hash_integridad := public.calcular_hash_evento(
    new.id, new.hash_anterior, new.tipo_evento, new.entidad, new.entidad_id,
    new.usuario_id, new.rol_usuario, new.descripcion, new.datos, new.created_at);
  return new;
end $$;

drop trigger if exists eventos_auditoria_hash on public.eventos_auditoria;
create trigger eventos_auditoria_hash before insert on public.eventos_auditoria
for each row execute function public.trg_eventos_auditoria_hash();

-- Trigger de inmutabilidad (append-only)
create or replace function public.trg_eventos_auditoria_inmutable()
returns trigger language plpgsql as $$
begin
  raise exception 'eventos_auditoria es de solo inserción: % no permitido', tg_op using errcode = '42501';
end $$;

drop trigger if exists eventos_auditoria_no_update on public.eventos_auditoria;
create trigger eventos_auditoria_no_update before update or delete on public.eventos_auditoria
for each row execute function public.trg_eventos_auditoria_inmutable();

drop trigger if exists eventos_auditoria_no_truncate on public.eventos_auditoria;
create trigger eventos_auditoria_no_truncate before truncate on public.eventos_auditoria
for each statement execute function public.trg_eventos_auditoria_inmutable();

revoke insert, update, delete, truncate on public.eventos_auditoria from anon, authenticated;

-- Registro de eventos: única vía de escritura para usuarios autenticados
create or replace function public.registrar_evento(
  p_tipo text, p_entidad text default null, p_entidad_id text default null,
  p_descripcion text default null, p_datos jsonb default '{}'::jsonb
) returns bigint language plpgsql security definer set search_path = public as $$
declare v_id bigint;
begin
  if auth.uid() is null then raise exception 'No autenticado' using errcode = '28000'; end if;
  insert into public.eventos_auditoria (tipo_evento, entidad, entidad_id, usuario_id, descripcion, datos)
  values (p_tipo, p_entidad, p_entidad_id, auth.uid(), p_descripcion, coalesce(p_datos,'{}'::jsonb))
  returning id into v_id;
  return v_id;
end $$;
revoke all on function public.registrar_evento(text,text,text,text,jsonb) from public;
grant execute on function public.registrar_evento(text,text,text,text,jsonb) to authenticated;

-- Verificación de la cadena (solo ADMINISTRADOR): devuelve los eventos alterados
create or replace function public.verificar_cadena_auditoria()
returns table(evento_id bigint, valido boolean, motivo text)
language plpgsql security definer set search_path = public as $$
declare r record; v_prev text := 'GENESIS'; v_calc text;
begin
  if public.current_user_role() is distinct from 'ADMINISTRADOR' then
    raise exception 'Solo el administrador puede verificar la auditoría' using errcode = '42501';
  end if;
  for r in select * from public.eventos_auditoria order by id loop
    v_calc := public.calcular_hash_evento(r.id, r.hash_anterior, r.tipo_evento, r.entidad, r.entidad_id,
              r.usuario_id, r.rol_usuario, r.descripcion, r.datos, r.created_at);
    if r.hash_anterior <> v_prev then
      evento_id := r.id; valido := false; motivo := 'Cadena rota: hash_anterior no coincide'; return next;
    elsif r.hash_integridad <> v_calc then
      evento_id := r.id; valido := false; motivo := 'Contenido alterado: hash no coincide'; return next;
    end if;
    v_prev := r.hash_integridad;
  end loop;
  return;
end $$;
revoke all on function public.verificar_cadena_auditoria() from public;
grant execute on function public.verificar_cadena_auditoria() to authenticated;

