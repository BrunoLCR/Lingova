-- ============================================================
-- FUNCIÓN: adjuntar comprobante (ADMINISTRADOR o EMPRESA dueña del pago)
-- ============================================================
create or replace function public.adjuntar_comprobante(p_pago_id bigint, p_path text, p_nombre text)
returns void language plpgsql security definer set search_path = public as $$
declare v_pago public.pagos;
begin
  select * into v_pago from public.pagos where id = p_pago_id;
  if not found then raise exception 'Pago no encontrado' using errcode = 'P0002'; end if;
  if public.current_user_role() = 'ADMINISTRADOR'
     or (public.current_user_role() = 'EMPRESA' and v_pago.empresa_id = public.current_empresa_id()) then
    if v_pago.estado = 'ANULADO' then raise exception 'El pago está anulado' using errcode = '22023'; end if;
    update public.pagos set comprobante_path = p_path, comprobante_nombre = p_nombre where id = p_pago_id;
  else
    raise exception 'Sin permisos sobre este pago' using errcode = '42501';
  end if;
end $$;
revoke all on function public.adjuntar_comprobante(bigint,text,text) from public;
grant execute on function public.adjuntar_comprobante(bigint,text,text) to authenticated;

