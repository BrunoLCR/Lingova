    insert into public.eventos_auditoria (tipo_evento, entidad, entidad_id, usuario_id, descripcion, datos)
    select 'MIGRACION_APF1', 'audit_events', a.id::text, a.user_id,
           coalesce(a.event_type,'') || ': ' || coalesce(a.description,''),
           jsonb_build_object('fecha_original', a.created_at)
    from public.audit_events a order by a.id;
  end if;
end $$;

