-- Catálogo: un registro por (curso, docente) con indicador de matrícula vigente
create or replace function public.catalogo_cursos()
returns table(curso_id bigint, nombre text, nivel text, descripcion text, precio numeric,
              docente_id uuid, docente_nombre text, ya_matriculado boolean)
language plpgsql stable security definer set search_path = public as $$
#variable_conflict use_column
begin
  if not public.tiene_permiso('matriculas:autogestionar') then
    raise exception 'Sin permiso matriculas:autogestionar' using errcode = '42501';
  end if;
  return query
  select c.id, c.name, c.level, c.description, c.precio, d.id, d.full_name,
         exists (select 1 from public.enrollments e
                 where e.student_id = auth.uid() and e.course_id = c.id and e.status <> 'RETIRADA')
  from public.courses c
  join public.cursos_docentes cd on cd.curso_id = c.id
  join public.profiles d on d.id = cd.docente_id
  where c.status = 'ACTIVO' and d.status = 'ACTIVO' and d.role = 'PROFESOR'
  order by c.name, d.full_name;
end $$;

-- Matrícula con pago simulado
create or replace function public.matricular_estudiante(p_curso bigint, p_docente uuid, p_metodo text)
returns table(matricula_id bigint, referencia text, monto numeric, curso text)
language plpgsql security definer set search_path = public as $$
#variable_conflict use_column
declare v_precio numeric; v_nombre text; v_ref text; v_id bigint; v_prev public.enrollments;
begin
  if not public.tiene_permiso('matriculas:autogestionar') then
    raise exception 'Sin permiso matriculas:autogestionar' using errcode = '42501';
  end if;
  if upper(coalesce(p_metodo, '')) not in ('TARJETA', 'YAPE', 'PLIN') then
    raise exception 'Método de pago no permitido' using errcode = '22023';
  end if;
  select c.precio, c.name into v_precio, v_nombre from public.courses c where c.id = p_curso and c.status = 'ACTIVO';
  if not found then raise exception 'Curso no disponible' using errcode = '22023'; end if;
  if not exists (select 1 from public.cursos_docentes cd join public.profiles d on d.id = cd.docente_id
                 where cd.curso_id = p_curso and cd.docente_id = p_docente and d.status = 'ACTIVO' and d.role = 'PROFESOR') then
    raise exception 'El docente no dicta este curso' using errcode = '22023';
  end if;

  v_ref := 'SIM-' || upper(substr(md5(random()::text || clock_timestamp()::text), 1, 10));
  select * into v_prev from public.enrollments e where e.student_id = auth.uid() and e.course_id = p_curso;
  if found then
    if v_prev.status <> 'RETIRADA' then raise exception 'Ya estás matriculado en este curso' using errcode = '23505'; end if;
    update public.enrollments
       set status = 'ACTIVA', progress = 0, docente_id = p_docente, enrolled_at = now(),
           monto_pagado = v_precio, pago_simulado_ref = v_ref, metodo_pago_simulado = upper(p_metodo)
     where id = v_prev.id returning id into v_id;
  else
    insert into public.enrollments (student_id, course_id, docente_id, progress, status, monto_pagado, pago_simulado_ref, metodo_pago_simulado)
    values (auth.uid(), p_curso, p_docente, 0, 'ACTIVA', v_precio, v_ref, upper(p_metodo))
    returning id into v_id;
  end if;

  insert into public.eventos_auditoria (tipo_evento, entidad, entidad_id, usuario_id, descripcion, datos)
  values ('MATRICULA_AUTOGESTIONADA', 'enrollments', v_id::text, auth.uid(),
          'Matrícula en "' || v_nombre || '" con pago simulado ' || v_ref,
          jsonb_build_object('curso_id', p_curso, 'docente_id', p_docente, 'monto', v_precio,
                             'metodo', upper(p_metodo), 'referencia', v_ref, 'simulado', true));
  return query select v_id, v_ref, v_precio, v_nombre;
end $$;

-- Nombres de los docentes de mis cursos (el estudiante no puede leer profiles de docentes directamente)
create or replace function public.nombres_docentes_matricula()
returns table(id uuid, full_name text)
